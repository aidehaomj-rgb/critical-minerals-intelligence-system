from pathlib import Path


root = Path(r"D:\codex\XG执法\2026_案例库")
data = json.loads((root / "重复主体候选.json").read_text(encoding="utf-8"))
catalog = {row.split(',', 1)[0].strip('"'): row for row in (root / "case_catalog.csv").read_text(encoding="utf-8-sig").splitlines()[1:]}
subjects = {item["entity"]: item for item in data["operational_subjects"]}
priority = [
    ("深圳润丰成贸易发展有限公司", "高", "跨6个案件包；在发货人或收货人字段出现。与“香港潤豐貿易發展有限公司”名称相近，但是否同一控制关系须以登记、地址、电话及报关主体信息核验。"),
    ("香港潤豐貿易發展有限公司", "高", "跨4个案件包；在发货人或收货人字段出现，并与深圳润丰成的案件集合高度重叠。仅作为名称/交易链路线索，不推定关联。"),
    ("DORTOO TECHNOLOGY LIMITED", "中", "跨4个案件包；均为申报人名称字段。需首先确认其是否为报关/物流服务商，再核对是否实际货主。"),
    ("HUNG YU LOGISTICS GROUP LIMITED", "中", "跨3个案件包；均为申报人名称。名称显示物流属性，应优先按服务商而非涉案主体核验。"),
    ("MAYTEX LOGISTICS LIMITED", "中", "跨3个案件包；均为申报人名称。应核验申报代理身份、委托关系及对应提运单。"),
    ("深圳市和宏物流有限公司", "中", "跨3个案件包；出现在发货人或收货人字段。需核验其实际贸易角色与物流服务角色。"),
    ("BEYOND DIAMOND LIMITED", "中", "跨2个协查案件包；分别出现为发货人和申报人，建议按公司编号、地址及提单/报关单号核验。"),
]

rows = []
for name, level, note in priority:
    item = subjects.get(name)
    if not item:
        continue
    rows.append(f"| {level} | {name} | {item['case_count']} | {', '.join(item['case_ids'])} | {', '.join(item['roles'])} | {note} |")

report = """# 重复主体筛查与海关数据库核查清单

## 结论边界

本清单从 131 份 XLSX 报关/贸易附件中，按**标准化名称在不同案件包中重复出现**筛选。它证明的是该名称被记录在多个案件材料内，不证明该人或企业被处罚、被立案、明知或参与违法。查询、协查和情报件尤其不能与最终处理结论混同。

## 优先企业线索

| 优先级 | 名称 | 跨案件包数 | 案件编号 | 表内角色 | 核查理由与边界 |
| --- | --- | ---: | --- | --- | --- |
""" + "\n".join(rows) + """

## 可归纳的规律

1. **重复主体集中在交易链条中段。** 最有价值的主体同时出现在发货人、收货人或申报人字段；但申报人、货代和承运人本身高频出现，不能仅以频次列为风险主体。
2. **名称相近、案件集合重叠是重要而未闭环的关联信号。** “深圳润丰成贸易发展有限公司”与“香港潤豐貿易發展有限公司”在四个案件包中同步出现，适合优先核对地址、电话、法定代表人/董事、银行账户、报关单号和上下游货主；当前材料不足以认定二者关联。
3. **同一批历史贸易数据会被多个协查件复用。** 因此“跨案件包数”不能等同于独立查获次数；应进一步按报关单号、提运单号、日期、集装箱号去重。
4. **物流/承运平台必须剔除后再排序。** 例如 FedEx、EVA Air、UPS、航空公司和码头/船公司在多案出现，更可能反映渠道覆盖，不宜作为“多次被查企业”结论。

## 建议在海关数据库优先核验的字段

1. 以主体名称（含繁简体、英文名、常见缩写）查报关单；记录统一社会信用代码、境外注册编号、地址和电话。
2. 对上表案件号分别提取报关单号、提运单/AWB、集装箱号、日期、申报人、发货人、收货人、商品名称、HS 编码、重量和申报价值。
3. 对“深圳润丰成/香港潤豐”做双向穿透：核对是否在同一票中互为发收货方，及是否共用地址、电话、联系人、账户或报关代理。
4. 对申报/物流主体另建“服务商”标签；只有在其为实际收发货方、被处罚主体或明知参与证据充分时，才与一般物流服务区分处理。
5. 对人员信息以证件号、电话、地址和授权文件交叉确认；当前结构化附件未形成足以可靠判定“同一自然人跨案”的标准化结果。

## 原始证据位置

每个候选的文件、工作表、字段和值详见 `重复主体候选.json`；原件位于 `raw_cases/<案件编号>/`。
"""
(root / "重复主体筛查与核查清单.md").write_text(report, encoding="utf-8")
